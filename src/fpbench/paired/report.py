"""Rendering the paired comparison, in the words it is allowed to use.

Most of this module is vocabulary discipline. The numbers are already computed
and verified by the time anything here runs; what the report adds is the risk of
saying something the numbers do not support.

So the section headings are fixed, the transition labels are directional and
neutral — "moved from MATCH to NON_MATCH", never "degraded" — and the two
sections a reader will most want to collapse into one, the per-run conditional
FNMRs, are kept apart with their differing denominators printed next to them.

Every percentage is a rendering of two integers that are printed beside it. The
report is regenerated byte for byte during verification, so a change to any of
this shows up as a mismatch rather than as a quietly different document
(spec section 75).
"""

